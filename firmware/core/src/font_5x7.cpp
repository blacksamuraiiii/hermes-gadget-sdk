bool bitmap(uint32_t cp, int* w, int* h, int* row_bytes, const uint8_t** rows) {
  if (cp >= 0x20 && cp <= 0x7E) {
    *w = kMetrics.glyph_w; *h = kMetrics.glyph_h; *row_bytes = 1; *rows = kAscii[cp - 0x20];
    return true;
  }
  if (cp >= 0xA0 && cp <= 0xFF) {
    *w = kMetrics.glyph_w; *h = kMetrics.glyph_h; *row_bytes = 1; *rows = kLatin1[cp - 0xA0];
    return true;
  }
  return false;
}

